export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    return localStorage.getItem(STORAGE_KEY) || localStorage.getItem('medshield_lang') || 'en';
  });

  const setLanguage = (langCode) => {
    if (translations[langCode]) {
      setLanguageState(langCode);
      localStorage.setItem(STORAGE_KEY, langCode);
      localStorage.setItem('medshield_lang', langCode);
    }
  };

  // Translation helper with dot notation or direct phrase mapping
  const t = (path, fallback = '') => {
    if (!path) return fallback;
    const langDict = translations[language] || translations.en;
    const enDict = translations.en;

    const resolve = (obj, p) => {
      if (!obj || typeof obj !== 'object') return undefined;
      const keys = p.split('.');
      let current = obj;
      for (const k of keys) {
        if (current && typeof current === 'object' && k in current) {
          current = current[k];
        } else {
          return undefined;
        }
      }
      return current;
    };

    // 1. Try dot-notation path in selected language
    let val = resolve(langDict, path);
    if (val !== undefined && typeof val === 'string') return val;

    // 2. If path has no dots, check top-level sections of selected language
    if (!path.includes('.')) {
      for (const section of ['nav', 'common', 'dashboard', 'cost', 'chat', 'compare', 'recommend', 'claims', 'upload_modal', 'facts_modal', 'auth']) {
        if (langDict[section] && typeof langDict[section] === 'object') {
          if (typeof langDict[section][path] === 'string') {
            return langDict[section][path];
          }
        }
      }
    }

    // 3. Fallback to English dot-notation or section if in English
    val = resolve(enDict, path);
    if (val !== undefined && typeof val === 'string' && language === 'en') return val;

    // 4. Try phrase dictionary for common fallback or path
    const targetPhrase = (fallback || path).trim();
    if (COMMON_PHRASES[language] && COMMON_PHRASES[language][targetPhrase]) {
      return COMMON_PHRASES[language][targetPhrase];
    }
    const cleanPath = path.trim();
    if (COMMON_PHRASES[language] && COMMON_PHRASES[language][cleanPath]) {
      return COMMON_PHRASES[language][cleanPath];
    }

    // 5. Fallback to provided fallback or last segment of path
    return fallback || path.split('.').pop();
  };

  const currentLanguageInfo = LANGUAGES.find(l => l.code === language) || LANGUAGES[0];

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        languages: LANGUAGES,
        currentLanguageInfo,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}

/**
 * Reusable Language Selector Dropdown Component
 */
export function LanguageSelector({ variant = 'default', direction = 'auto', className = '' }) {
  const { language, setLanguage, languages, currentLanguageInfo } = useLanguage();
  const [isOpen, setIsOpen] = useState(false);
  const [openUpward, setOpenUpward] = useState(direction === 'up');
  const dropdownRef = useRef(null);

  useEffect(() => {
    function handleClickOutside(e) {
      if (dropdownRef.current && !dropdownRef.current.contains(e.target)) {
        setIsOpen(false);
      }
    }
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  const handleToggle = () => {
    if (!isOpen && dropdownRef.current) {
      if (direction === 'up') {
        setOpenUpward(true);
      } else if (direction === 'down') {
        setOpenUpward(false);
      } else {
        const rect = dropdownRef.current.getBoundingClientRect();
        // If space below is less than 300px, open upwards so UI doesn't get dragged down
        const spaceBelow = window.innerHeight - rect.bottom;
        setOpenUpward(spaceBelow < 300);
      }
    }
    setIsOpen(prev => !prev);
  };

  const buttonStyleClass =
    variant === 'dark'
      ? 'bg-white/[0.08] border border-white/[0.15] text-white hover:bg-white/[0.12]'
      : variant === 'compact'
      ? 'bg-[#062327]/05 border border-[#062327]/12 text-[#062327] hover:bg-[#062327]/10'
      : 'bg-white border border-[#062327]/15 text-[#062327] hover:bg-[#062327]/05 shadow-xs';

  const isUp = direction === 'up' || (direction === 'auto' && openUpward);

  return (
    <div ref={dropdownRef} className={`relative inline-block ${className}`}>
      <button
        type="button"
        onClick={handleToggle}
        className={`flex items-center gap-1.5 px-2.5 py-1.5 rounded-xl text-xs font-bold transition-all duration-200 cursor-pointer ${buttonStyleClass}`}
        aria-label="Select Language"
      >
        <Globe size={13} className="text-[#558187] flex-shrink-0" />
        <span className="font-semibold tracking-tight">{currentLanguageInfo.nativeName}</span>
        <ChevronDown size={11} className={`text-[#558187] transition-transform duration-200 ${isOpen ? 'rotate-180' : ''}`} />
      </button>

      {isOpen && (
        <div
          className={`absolute right-0 ${
            isUp ? 'bottom-full mb-2 origin-bottom-right' : 'top-full mt-2 origin-top-right'
          } w-52 bg-[#0c2024] text-white border border-white/10 rounded-2xl shadow-2xl overflow-hidden z-50 animate-fade-in backdrop-blur-xl`}
          style={{
            boxShadow: '0 20px 48px rgba(0,0,0,0.60), 0 0 0 1px rgba(255,255,255,0.08)',
          }}
        >
          <div className="px-3.5 py-2.5 border-b border-white/10 bg-white/[0.03]">
            <p className="text-[10px] text-[#d2f57b] uppercase tracking-wider font-extrabold">Choose Language</p>
          </div>
          <div className="max-h-56 overflow-y-auto scroll-area py-1 divide-y divide-white/[0.04]">
            {languages.map((lang) => {
              const isSelected = language === lang.code;
              return (
                <button
                  key={lang.code}
                  type="button"
                  onClick={() => {
                    setLanguage(lang.code);
                    setIsOpen(false);
                  }}
                  className={`w-full text-left px-3.5 py-2 text-xs flex items-center justify-between transition-colors cursor-pointer ${
                    isSelected
                      ? 'bg-[#d2f57b]/20 text-[#d2f57b] font-bold'
                      : 'text-zinc-200 hover:bg-white/[0.08] hover:text-white'
                  }`}
                >
                  <div className="flex items-center gap-2.5">
                    <span className="text-sm">{lang.flag}</span>
                    <div>
                      <p className="text-xs leading-none font-semibold">{lang.nativeName}</p>
                      <p className="text-[10px] text-zinc-400 mt-0.5">{lang.name}</p>
                    </div>
                  </div>
                  {isSelected && <Check size={13} className="text-[#d2f57b] flex-shrink-0" />}
                </button>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
}
